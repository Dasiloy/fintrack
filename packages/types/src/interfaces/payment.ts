// ---------------------------------------------------------------------------
// invoice.create / invoice.update / invoice.payment_failed
// ---------------------------------------------------------------------------

/** Shared data shape for all three invoice webhook events */
export interface InvoiceEventData {
  /** Environment: "live" or "test" */
  domain: string;
  /** Paystack invoice code (INV_xxx) */
  invoice_code: string;
  /** Invoice amount in kobo */
  amount: number;
  /** ISO 8601 billing period start */
  period_start: string;
  /** ISO 8601 billing period end */
  period_end: string;
  /** Invoice status e.g. "success", "pending" */
  status: string;
  /** Whether the invoice has been paid */
  paid: boolean;
  /** ISO 8601 timestamp when paid; null if unpaid */
  paid_at: string | null;
  /** Invoice description; null if not set */
  description: string | null;
  /** Card authorization used for this invoice */
  authorization: PaystackWebhookAuthorization;
  /** Associated subscription */
  subscription: PaystackWebhookNestedSubscription;
  /** Customer who was charged */
  customer: PaystackWebhookCustomer;
  /** Resulting transaction; may be empty object on payment_failed */
  transaction: PaystackWebhookNestedTransaction;
  /** ISO 8601 timestamp when the invoice was created */
  created_at: string;
}

export type InvoiceCreateEvent = PaystackWebhookEvent<InvoiceEventData>;
export type InvoiceUpdateEvent = PaystackWebhookEvent<InvoiceEventData>;
export type InvoicePaymentFailedEvent = PaystackWebhookEvent<InvoiceEventData>;

