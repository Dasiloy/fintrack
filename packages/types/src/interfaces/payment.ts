export type PaystackEventType =
  | 'charge.success'
  | 'invoice.create'
  | 'invoice.update'
  | 'invoice.payment_failed'
  | 'subscription.create'
  | 'subscription.disable'
  | 'subscription.not_renew'
  | 'subscription.expiring_cards';

//* Generic envelope — every Paystack webhook has this top-level shape
export interface PaystackWebhookEvent<T = unknown> {
  /** Paystack event type */
  event: PaystackEventType;
  /** Event-specific payload */
  data: T;
}

//* Shared sub-shapes reused across multiple event payloads

export interface PaystackWebhookAuthorization {
  /** Reusable card token — store encrypted */
  authorization_code: string;
  /** First 6 digits of the card */
  bin: string;
  /** Last 4 digits of the card */
  last4: string;
  /** Card expiry month (MM) */
  exp_month: string;
  /** Card expiry year (YYYY) */
  exp_year: string;
  /** Payment channel; absent on some older events */
  channel?: PaysatckChannels;
  /** Card scheme and type e.g. "visa DEBIT" */
  card_type: string;
  /** Issuing bank name */
  bank: string;
  /** ISO 3166-1 alpha-2 country code */
  country_code: string;
  /** Card brand */
  brand: string;
  /** Whether this authorization can be reused for future charges */
  reusable?: boolean;
  /** Paystack authorization signature; absent on some older events */
  signature?: string;
  /** Account name on the card; null if unavailable */
  account_name: string | null;
}

export interface PaystackWebhookCustomer {
  /** Paystack internal customer ID; absent on some older events */
  id?: number;
  /** Customer first name; null if not provided */
  first_name: string | null;
  /** Customer last name; null if not provided */
  last_name: string | null;
  /** Customer email address */
  email: string;
  /** Paystack customer code (CUS_xxx) */
  customer_code: string;
  /** Customer phone; null if not provided */
  phone: string | null;
  /** Arbitrary metadata stored on the customer */
  metadata: Record<string, unknown> | null;
  /** Paystack risk classification */
  risk_action: string;
  /** E.164 formatted phone; absent on older events */
  international_format_phone?: string | null;
}

export interface PaystackWebhookPlan {
  /** Paystack internal plan ID; absent on subscription.create */
  id?: number;
  /** Human-readable plan name */
  name: string;
  /** Paystack plan code (PLN_xxx) */
  plan_code: string;
  /** Plan description; null if not set */
  description: string | null;
  /** Recurring amount in kobo */
  amount: number;
  /** Billing interval e.g. "monthly", "annually" */
  interval: string;
  /** Whether Paystack sends invoice emails */
  send_invoices: boolean;
  /** Whether Paystack sends SMS notifications */
  send_sms: boolean;
  /** Plan currency */
  currency: string;
}

/** Subscription object nested inside invoice event payloads */
export interface PaystackWebhookNestedSubscription {
  /** Current subscription status */
  status: string;
  /** Subscription code (SUB_xxx) */
  subscription_code: string;
  /** Email token required for disable/enable; present on invoice.create, absent on invoice.update */
  email_token?: string;
  /** Recurring amount in kobo */
  amount: number;
  /** Cron expression for the billing schedule */
  cron_expression: string;
  /** ISO 8601 date of the next scheduled charge */
  next_payment_date: string | null;
  /** Invoice code of any currently open invoice; null if none */
  open_invoice: string | null;
}

/** Transaction object nested inside invoice event payloads */
export interface PaystackWebhookNestedTransaction {
  /** Transaction reference; absent on invoice.payment_failed with no charge attempt */
  reference?: string;
  /** Transaction status; absent if no charge was attempted */
  status?: string;
  /** Charged amount in kobo */
  amount?: number;
  /** Transaction currency */
  currency?: string;
}

